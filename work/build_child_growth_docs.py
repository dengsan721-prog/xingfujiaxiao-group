def set_run_font(run, size=None, bold=False, color=None):
    run.font.name = "Microsoft YaHei"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    run._element.rPr.rFonts.set(qn("w:ascii"), "Microsoft YaHei")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Microsoft YaHei")
    if size:
        run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def set_paragraph(paragraph, before=0, after=6, line=1.12):
    paragraph.paragraph_format.space_before = Pt(before)
    paragraph.paragraph_format.space_after = Pt(after)
    paragraph.paragraph_format.line_spacing = line


def add_heading(doc, text, level=1):
    p = doc.add_paragraph()
    set_paragraph(p, before=10 if level == 1 else 6, after=5)
    style = f"Heading {level}" if level else "Title"
    p.style = doc.styles[style]
    r = p.add_run(text)
    set_run_font(r, size=18 if level == 1 else 13, bold=True, color=(0, 0, 0))
    return p


def add_body(doc, text, bold_prefix=None):
    p = doc.add_paragraph()
    set_paragraph(p)
    if bold_prefix and text.startswith(bold_prefix):
        r1 = p.add_run(bold_prefix)
        set_run_font(r1, size=10.5, bold=True)
        r2 = p.add_run(text[len(bold_prefix):])
        set_run_font(r2, size=10.5)
    else:
        r = p.add_run(text)
        set_run_font(r, size=10.5)
    return p


def add_bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    set_paragraph(p, after=3)
    r = p.add_run(text)
    set_run_font(r, size=10)


def add_numbered(doc, text):
    p = doc.add_paragraph(style="List Number")
    set_paragraph(p, after=3)
    r = p.add_run(text)
    set_run_font(r, size=10)


def sanitize_filename(name):
    name = re.sub(r"[\\/:*?\"<>|]", "", name)
    return name.replace(" ", "")


