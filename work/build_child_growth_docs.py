def build_doc(item):
    doc = Document()
    configure_document(doc)

    p = doc.add_paragraph(style="Title")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("董事长（孩子）长成记")
    set_run_font(r, size=22, bold=True)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_paragraph(p, after=12)
    r = p.add_run(item["subtitle"])
    set_run_font(r, size=16, bold=True)

    add_heading(doc, "核心精要", 1)
    add_body(doc, item["core"])
    add_body(doc, "使用方式：教练每天复制当天从【今日小角色】到【教练收口】的完整内容发到群里即可。每天提前或现场指定 2 到 4 个孩子担任角色，尤其让“游戏官”带领大家玩，教练只需要补充提醒和收尾。孩子只需要按提示回复、参与小游戏、完成一个小作业。")

    add_heading(doc, "14 天安排总览", 1)
    for i, day in enumerate(item["days"], start=1):
        add_bullet(doc, f"第 {i} 天：{day['title']}")

    doc.add_page_break()
    add_heading(doc, "每天群发内容", 1)
    for i, day in enumerate(item["days"], start=1):
        day["roles"] = ROLE_SETS[(i - 1) % len(ROLE_SETS)]
        add_heading(doc, f"第 {i} 天  {day['title']}", 2)
        add_copy_block(doc, day)
        if i != len(item["days"]):
            doc.add_paragraph()

    filename = f"董事长（孩子）长成记_{sanitize_filename(item['subtitle'])}.docx"
    path = OUT_DIR / filename
    doc.save(path)
    return path


